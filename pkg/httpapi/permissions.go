// ManagementPermissions maps the actual registered HTTP method and pattern,
// including stream routes. It intentionally omits the unauthenticated OPTIONS
// preflight, which cannot invoke any management action.
func ManagementPermissions() map[string]managementpermission.Permission {
	out := make(map[string]managementpermission.Permission, len(v2Routes))
	for _, route := range v2Routes {
		out[v2RoutePattern(route)] = v2Permissions[route.endpoint]
	}
	return out
}
