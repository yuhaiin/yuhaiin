package trafficcontrol

import "encoding/binary"

func Classify(b []byte) Classification {
	return Classification{Host: HostHash(b), Flow: FlowHash(b), Weight: PacketWeight(b)}
}

// HostHash uses the destination IP of packets exiting the stack (the
// inbound client on TUN replies) as the trusted host identity. Unparseable
// packets fall back to one low-priority host group. IPv4/IPv6 keys do not
// expose addresses as metric labels.
func HostHash(b []byte) uint64 {
	var addr []byte
	switch {
	case len(b) >= 20 && b[0]>>4 == 4:
		addr = b[16:20]
	case len(b) >= 40 && b[0]>>4 == 6:
		addr = b[24:40]
	default:
		return 0
	}
	h := uint64(14695981039346656037)
	for _, v := range addr {
		h ^= uint64(v)
		h *= 1099511628211
	}
	h ^= uint64(b[0] >> 4)
	return h * 1099511628211
}

// FlowHash is a cheap classifier for packets generated by this stack.
// It avoids reparsing checksums, heap allocation, and dynamic flow IDs on each
// enqueue. Fragment/non-TCP/UDP packets are grouped by their IP endpoints and
// protocol. Hash collisions share a queue but never break packet ownership.
func FlowHash(b []byte) uint64 {
	const offset64 = uint64(14695981039346656037)
	const prime64 = uint64(1099511628211)
	hash := offset64
	add := func(data []byte) {
		for _, v := range data {
			hash ^= uint64(v)
			hash *= prime64
		}
	}
	if len(b) < 1 {
		return 0
	}
	switch b[0] >> 4 {
	case 4:
		if len(b) < 20 {
			return 0
		}
		header := int(b[0]&15) * 4
		if header < 20 || header > len(b) {
			return 0
		}
		add(b[:1])
		add(b[9:10])
		add(b[12:20])
		frag := binary.BigEndian.Uint16(b[6:8])
		if frag&0x3fff == 0 && (b[9] == 6 || b[9] == 17) && header+4 <= len(b) {
			add(b[header : header+4])
		}
	case 6:
		if len(b) < 40 {
			return 0
		}
		add(b[:1])
		add(b[6:7])
		add(b[8:40])
		next, off := b[6], 40
		fragmented := false
		for range 8 {
			if next == 44 {
				// Fragmented packets deliberately share the same endpoint
				// queue: non-initial fragments have no transport ports.
				fragmented = true
				break
			}
			if next != 0 && next != 43 && next != 60 {
				break
			}
			if off+2 > len(b) {
				return hash
			}
			headerSize := (int(b[off+1]) + 1) * 8
			if off+headerSize > len(b) {
				return hash
			}
			next, off = b[off], off+headerSize
		}
		if !fragmented && (next == 6 || next == 17) && off+4 <= len(b) {
			add(b[off : off+4])
		}
	default:
		return 0
	}
	return hash
}

// PacketWeight reserves a bounded extra byte-service share for
// internally generated transport control packets. DSCP and DNS port numbers
// are deliberately ignored: external users must not create a priority bypass.
func PacketWeight(b []byte) int {
	if len(b) == 0 {
		return 1
	}
	proto := uint8(0)
	offset := 0
	switch b[0] >> 4 {
	case 4:
		if len(b) < 20 {
			return 1
		}
		offset = int(b[0]&15) * 4
		if offset < 20 || len(b) < offset {
			return 1
		}
		if binary.BigEndian.Uint16(b[6:8])&0x3fff != 0 {
			return 1
		}
		proto = b[9]
	case 6:
		if len(b) < 40 {
			return 1
		}
		proto = b[6]
		offset = 40
	default:
		return 1
	}
	if proto == 1 || proto == 58 {
		return 2
	}
	if proto != 6 || len(b) < offset+20 {
		return 1
	}
	tcp := b[offset:]
	if tcp[13]&0x07 != 0 {
		return 4
	} // FIN, SYN, RST
	h := int(tcp[12]>>4) * 4
	if h >= 20 && h == len(tcp) {
		return 4
	} // pure ACK/control
	return 1
}
