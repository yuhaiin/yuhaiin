// UploadProtocolHeader identifies the opt-in endpoint protocol, not an arbitrary
// POST sink. A successful HEAD handshake must precede the single streaming POST.
const UploadProtocolHeader = "Yuhaiin-Upload-Test"
const UploadProtocolVersion = "1"
const MaxUploadAcknowledgementBytes = 4096

type UploadAcknowledgement struct {
	Version       int   `json:"version"`
	ReceivedBytes int64 `json:"receivedBytes"`
}

func MeasureUpload(ctx context.Context, p netapi.Proxy, request contract.SpeedTestRequest) (contract.ThroughputMeasurement, error) {
	return measureUpload(ctx, p, request, nil)
}
func measureUpload(ctx context.Context, p netapi.Proxy, request contract.SpeedTestRequest, tlsConfig *tls.Config) (result contract.ThroughputMeasurement, resultErr error) {
	r, err := ValidateSpeedTest(request)
	if err == nil && r.Direction != "upload" {
		err = errors.New("upload measurement requires upload direction")
	}
	if err != nil {
		return contract.ThroughputMeasurement{}, err
	}
	ctx, cancel := context.WithTimeout(ctx, time.Duration(r.TimeoutMS)*time.Millisecond)
	defer cancel()
	// Bound connection wrappers can observe the close before net/http observes
	// cancellation. Preserve the caller/timeout classification across that race.
	defer func() {
		if resultErr != nil && ctx.Err() != nil {
			resultErr = ctx.Err()
		}
	}()
	result = contract.ThroughputMeasurement{At: time.Now().UnixMilli(), Target: r.URL, Direction: "upload"}
	client, closeClient := speedHTTPClient(ctx, p, tlsConfig)
	defer closeClient()
	head, err := http.NewRequestWithContext(ctx, http.MethodHead, r.URL, nil)
	if err != nil {
		return result, err
	}
	head.Header.Set(UploadProtocolHeader, UploadProtocolVersion)
	head.Header.Set("Cache-Control", "no-cache, no-store")
	response, err := client.Do(head)
	if err != nil {
		return result, err
	}
	_ = response.Body.Close()
	if (response.StatusCode != http.StatusOK && response.StatusCode != http.StatusNoContent) || response.Header.Get(UploadProtocolHeader) != UploadProtocolVersion {
		return result, errors.New("endpoint did not explicitly advertise the upload test protocol")
	}
	body := &uploadBody{ctx: ctx, limit: r.MaxBytes, duration: time.Duration(r.DurationMS) * time.Millisecond}
	// A non-rewindable, unknown-length body permits a normal duration-limited EOF.
	// No GetBody/idempotency key or redirect can replay this non-idempotent POST.
	req, err := http.NewRequestWithContext(ctx, http.MethodPost, r.URL, body)
	if err != nil {
		return result, err
	}
	req.Header.Set(UploadProtocolHeader, UploadProtocolVersion)
	req.Header.Set("Content-Type", "application/octet-stream")
	req.Header.Set("Accept", "application/json")
	req.Header.Set("Accept-Encoding", "identity")
	req.Header.Set("Cache-Control", "no-cache, no-store")
	response, err = client.Do(req)
	if err != nil {
		return result, err
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK || response.Header.Get(UploadProtocolHeader) != UploadProtocolVersion {
		return result, errors.New("upload endpoint did not acknowledge the test")
	}
	media, _, err := mime.ParseMediaType(response.Header.Get("Content-Type"))
	if err != nil || media != "application/json" {
		return result, errors.New("upload acknowledgement requires JSON")
	}
	if encoding := response.Header.Get("Content-Encoding"); encoding != "" && encoding != "identity" {
		return result, errors.New("compressed upload acknowledgement is unsupported")
	}
	raw, err := io.ReadAll(io.LimitReader(response.Body, MaxUploadAcknowledgementBytes+1))
	if err != nil {
		return result, err
	}
	if len(raw) > MaxUploadAcknowledgementBytes {
		return result, errors.New("upload acknowledgement exceeds its limit")
	}
	var ack UploadAcknowledgement
	if err := json.Unmarshal(raw, &ack, json.RejectUnknownMembers(true)); err != nil {
		return result, errors.New("invalid upload acknowledgement")
	}
	start, n, finished := body.snapshot()
	elapsed := time.Since(start)
	result.Bytes, result.DurationMS = n, elapsed.Milliseconds()
	if err := ctx.Err(); err != nil {
		return result, err
	}
	if !finished || start.IsZero() || elapsed <= 0 || n < 1024 || ack.Version != 1 || ack.ReceivedBytes != n {
		return result, errors.New("upload acknowledgement does not match the complete test body")
	}
	result.OK, result.Samples, result.UploadMbps = true, 1, float64(n)*8/elapsed.Seconds()/1e6
	return result, nil
}

// Generated bytes are encrypted by HTTPS. Only a small transport buffer exists;
// neither an archive-sized request body nor an unbounded producer is allocated.
// Mutex protection covers the HTTP writer and an early-response reader.
type uploadBody struct {
	ctx              context.Context
	limit            int64
	duration         time.Duration
	mu               sync.Mutex
	start            time.Time
	bytes            int64
	finished, closed bool
}

func (b *uploadBody) Read(p []byte) (int, error) {
	b.mu.Lock()
	defer b.mu.Unlock()
	if err := b.ctx.Err(); err != nil {
		return 0, err
	}
	if b.closed {
		return 0, io.ErrClosedPipe
	}
	if len(p) == 0 {
		return 0, nil
	}
	if b.start.IsZero() {
		b.start = time.Now()
	}
	if b.bytes >= b.limit || time.Since(b.start) >= b.duration {
		b.finished = true
		return 0, io.EOF
	}
	n := min(int64(len(p)), b.limit-b.bytes)
	if _, err := rand.Read(p[:n]); err != nil {
		return 0, err
	}
	b.bytes += n
	return int(n), nil
}
func (b *uploadBody) Close() error { b.mu.Lock(); b.closed = true; b.mu.Unlock(); return nil }
func (b *uploadBody) snapshot() (time.Time, int64, bool) {
	b.mu.Lock()
	defer b.mu.Unlock()
	return b.start, b.bytes, b.finished
}
