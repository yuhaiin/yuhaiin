package masque

import (
	"encoding/binary"
	"errors"
	"fmt"

	"github.com/Asutorufa/yuhaiin/pkg/log"
	"github.com/quic-go/quic-go"
	"golang.org/x/net/icmp"
	"golang.org/x/net/ipv4"
	"golang.org/x/net/ipv6"
)

const (
	// CONNECT-IP's IP packet context ID is 0, encoded as a one-byte QUIC varint.
	cloudflareIPContextID = byte(0)
	cloudflareMinMTU      = 1280
)

type cloudflareDatagramSender interface {
	SendDatagram([]byte) error
}

// sendCloudflareIPPacket follows usque's Cloudflare-specific sending behavior:
// validate the IP header and decrement TTL / Hop Limit, but do not enforce
// routes advertised by the remote CONNECT-IP peer. Cloudflare's endpoint doesn't
// advertise arbitrary Internet destinations, so the RFC-compliant route check
// in connect-ip-go would otherwise discard ordinary IPv4/IPv6 traffic.
//
// Only the MASQUE Cloudflare path uses this function. connect-ip-go continues to
// handle all control capsules, incoming packets, and connection shutdown.
func sendCloudflareIPPacket(sender cloudflareDatagramSender, packet []byte) ([]byte, error) {
	if err := validateCloudflareOutgoingPacket(packet); err != nil {
		// Match usque's WritePacket behavior for packets that can't be forwarded.
		log.Info("dropping proxied packet", "len", len(packet), "err", err)
		return nil, nil
	}

	datagram := make([]byte, len(packet)+1)
	datagram[0] = cloudflareIPContextID
	copy(datagram[1:], packet)

	if err := sender.SendDatagram(datagram); err != nil {
		if _, ok := errors.AsType[*quic.DatagramTooLargeError](err); ok {
			// Preserve connect-ip-go / usque's ICMP Packet Too Big feedback so
			// oversized IPv6 TCP packets don't silently stall.
			return composeCloudflarePacketTooBig(packet, cloudflareMinMTU)
		}
		return nil, err
	}
	return nil, nil
}

// validateCloudflareOutgoingPacket mirrors the checks in usque's customized
// connect-ip-go, without its requirement for a remote-advertised IP route.
func validateCloudflareOutgoingPacket(packet []byte) error {
	if len(packet) == 0 {
		return errors.New("connect-ip: empty packet")
	}

	switch packet[0] >> 4 {
	case 4:
		if len(packet) < ipv4.HeaderLen {
			return errors.New("connect-ip: IPv4 packet too short")
		}
		headerLen := int(packet[0]&0x0f) * 4
		if headerLen < ipv4.HeaderLen || headerLen > len(packet) {
			return errors.New("connect-ip: invalid IPv4 header length")
		}
		if packet[8] <= 1 {
			return fmt.Errorf("connect-ip: datagram TTL too small: %d", packet[8])
		}
		packet[8]--
		binary.BigEndian.PutUint16(packet[10:12], 0)
		binary.BigEndian.PutUint16(packet[10:12], cloudflareIPv4Checksum(packet[:headerLen]))
	case 6:
		if len(packet) < ipv6.HeaderLen {
			return errors.New("connect-ip: IPv6 packet too short")
		}
		if packet[7] <= 1 {
			return fmt.Errorf("connect-ip: datagram Hop Limit too small: %d", packet[7])
		}
		packet[7]--
	default:
		return fmt.Errorf("connect-ip: unknown IP version: %d", packet[0]>>4)
	}
	return nil
}

func cloudflareIPv4Checksum(header []byte) uint16 {
	var sum uint32
	for i := 0; i+1 < len(header); i += 2 {
		sum += uint32(binary.BigEndian.Uint16(header[i : i+2]))
	}
	for sum>>16 != 0 {
		sum = (sum & 0xffff) + (sum >> 16)
	}
	return ^uint16(sum)
}

// composeCloudflarePacketTooBig is the same ICMP feedback generated by
// connect-ip-go on a QUIC DatagramTooLargeError, with the MTU fixed to 1280.
func composeCloudflarePacketTooBig(packet []byte, mtu int) ([]byte, error) {
	var msg *icmp.Message
	var pseudoHeader []byte

	switch packet[0] >> 4 {
	case 4:
		const maxQuote = 576 - ipv4.HeaderLen - 8
		msg = &icmp.Message{
			Type: ipv4.ICMPTypeDestinationUnreachable,
			Code: 4,
			Body: &icmp.PacketTooBig{
				MTU:  mtu,
				Data: packet[:min(len(packet), maxQuote)],
			},
		}
	case 6:
		msg = &icmp.Message{
			Type: ipv6.ICMPTypePacketTooBig,
			Body: &icmp.PacketTooBig{
				MTU:  mtu,
				Data: packet[:min(len(packet), 1232)],
			},
		}
		pseudoHeader = icmp.IPv6PseudoHeader(packet[24:40], packet[8:24])
	default:
		return nil, fmt.Errorf("connect-ip: unknown IP version: %d", packet[0]>>4)
	}

	icmpBody, err := msg.Marshal(pseudoHeader)
	if err != nil {
		return nil, fmt.Errorf("connect-ip: failed to marshal ICMP: %w", err)
	}

	if packet[0]>>4 == 4 {
		var hdr [ipv4.HeaderLen]byte
		hdr[0] = 0x45
		binary.BigEndian.PutUint16(hdr[2:4], uint16(len(hdr)+len(icmpBody)))
		hdr[8] = 64
		hdr[9] = 1
		copy(hdr[12:16], packet[16:20])
		copy(hdr[16:20], packet[12:16])
		binary.BigEndian.PutUint16(hdr[10:12], cloudflareIPv4Checksum(hdr[:]))
		return append(hdr[:], icmpBody...), nil
	}

	var hdr [ipv6.HeaderLen]byte
	hdr[0] = 6 << 4
	binary.BigEndian.PutUint16(hdr[4:6], uint16(len(icmpBody)))
	hdr[6] = 58
	hdr[7] = 64
	copy(hdr[8:24], packet[24:40])
	copy(hdr[24:40], packet[8:24])
	return append(hdr[:], icmpBody...), nil
}
