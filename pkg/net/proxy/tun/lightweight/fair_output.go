package lightweight

import (
	"encoding/binary"
	"time"
)

// dequeueOutput returns the next owned packet from the fair scheduling domain.
// Test-only stacks constructed without a scheduler retain the legacy channel
// semantics, including immediate batch draining and exact FIFO ordering.
func (s *Stack) dequeueOutput(wait bool) (*ownedBuffer, bool) {
	if s.fairOutput == nil {
		if !wait {
			select {
			case b := <-s.outgoing:
				return b, true
			default:
				return nil, false
			}
		}
		select {
		case <-s.done:
			return nil, false
		case b := <-s.outgoing:
			return b, true
		}
	}
	for {
		select {
		case <-s.done:
			return nil, false
		default:
		}
		packet, ok, discarded := s.fairOutput.Pop(time.Now())
		for _, b := range discarded {
			b.release() // Never release pooled buffers inside the scheduler lock.
			s.drops.Add(1)
		}
		if ok {
			// Space was released by the dequeue even if this packet is still
			// being written. TCP waiters need not poll a full queue.
			s.wakeOutput()
			return packet, true
		}
		if !wait {
			return nil, false
		}
		select {
		case <-s.done:
			return nil, false
		case <-s.fairOutput.Notify():
		}
	}
}

// outputFlowHash is a cheap classifier for packets generated by this stack.
// It avoids reparsing checksums, heap allocation, and dynamic flow IDs on each
// enqueue. Fragment/non-TCP/UDP packets are grouped by their IP endpoints and
// protocol. Hash collisions share a queue but never break packet ownership.
func outputFlowHash(packet *ownedBuffer) uint64 {
	if packet == nil || packet.offset < 0 || packet.offset >= len(packet.data) {
		return 0
	}
	b := packet.data[packet.offset:]
	const offset64 = uint64(14695981039346656037)
	const prime64 = uint64(1099511628211)
	hash := offset64
	add := func(data []byte) {
		for _, v := range data {
			hash ^= uint64(v)
			hash *= prime64
		}
	}
	if len(b) < 1 {
		return 0
	}
	switch b[0] >> 4 {
	case 4:
		if len(b) < 20 {
			return 0
		}
		header := int(b[0]&15) * 4
		if header < 20 || header > len(b) {
			return 0
		}
		add(b[:1])
		add(b[9:10])
		add(b[12:20])
		frag := binary.BigEndian.Uint16(b[6:8])
		if frag&0x3fff == 0 && (b[9] == 6 || b[9] == 17) && header+4 <= len(b) {
			add(b[header : header+4])
		}
	case 6:
		if len(b) < 40 {
			return 0
		}
		add(b[:1])
		add(b[6:7])
		add(b[8:40])
		next, off := b[6], 40
		fragmented := false
		for i := 0; i < 8; i++ {
			if next == 44 {
				// Fragmented packets deliberately share the same endpoint
				// queue: non-initial fragments have no transport ports.
				fragmented = true
				break
			}
			if next != 0 && next != 43 && next != 60 {
				break
			}
			if off+2 > len(b) {
				return hash
			}
			headerSize := (int(b[off+1]) + 1) * 8
			if off+headerSize > len(b) {
				return hash
			}
			next, off = b[off], off+headerSize
		}
		if !fragmented && (next == 6 || next == 17) && off+4 <= len(b) {
			add(b[off : off+4])
		}
	default:
		return 0
	}
	return hash
}

// outputPacketWeight reserves a bounded extra byte-service share for
// internally generated transport control packets. DSCP and DNS port numbers
// are deliberately ignored: external users must not create a priority bypass.
func outputPacketWeight(p *ownedBuffer) int {
	if p == nil || p.offset < 0 || p.offset >= len(p.data) {
		return 1
	}
	b := p.data[p.offset:]
	if len(b) == 0 {
		return 1
	}
	proto := uint8(0)
	offset := 0
	switch b[0] >> 4 {
	case 4:
		if len(b) < 20 {
			return 1
		}
		offset = int(b[0]&15) * 4
		if offset < 20 || len(b) < offset {
			return 1
		}
		if binary.BigEndian.Uint16(b[6:8])&0x3fff != 0 {
			return 1
		}
		proto = b[9]
	case 6:
		if len(b) < 40 {
			return 1
		}
		proto = b[6]
		offset = 40
	default:
		return 1
	}
	if proto == 1 || proto == 58 {
		return 2
	}
	if proto != 6 || len(b) < offset+20 {
		return 1
	}
	tcp := b[offset:]
	if tcp[13]&0x07 != 0 {
		return 4
	} // FIN, SYN, RST
	h := int(tcp[12]>>4) * 4
	if h >= 20 && h == len(tcp) {
		return 4
	} // pure ACK/control
	return 1
}
